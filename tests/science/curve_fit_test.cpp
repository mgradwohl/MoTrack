// Agreement between this port and the Java fixture (docs/curve-fitting.md#tolerances).

struct Tolerance
{
    double relative;
    double absolute;
};

/// Fits evaluated with + - * / only (and x^2 = x*x) are bitwise identical to Java.
constexpr Tolerance EXACT{.relative = 0.0, .absolute = 0.0};
/// Math.exp/sin/log/pow differ from <cmath> in the last bit. The finite-difference Hessian divides
/// sums of squares by (|p|+1)^2 1e-10, amplifying that bit by about 1e6 in each Newton step; the
/// minimizers stop at steps of 1e-12, so the minimum they report agrees to about 1e-9.
constexpr Tolerance TRANSCENDENTAL_PARAMETERS{.relative = 1e-7, .absolute = 1e-9};
/// Uncertainties are second differences of chi squared at a step of up to 1e-4 |p|, refitted each time.
constexpr Tolerance TRANSCENDENTAL_UNCERTAINTIES{.relative = 1e-4, .absolute = 1e-9};

bool close(double expected, double actual, Tolerance tolerance)
{
    if (std::isnan(expected) || std::isnan(actual))
    {
        return std::isnan(expected) && std::isnan(actual);
    }
    if (std::isinf(expected) || std::isinf(actual))
    {
        return expected == actual;
    }
    if (tolerance.relative == 0.0 && tolerance.absolute == 0.0)
    {
        return std::bit_cast<std::uint64_t>(expected) == std::bit_cast<std::uint64_t>(actual) || expected == actual;
    }
    return std::abs(expected - actual) <= tolerance.absolute + (tolerance.relative * std::max(std::abs(expected), std::abs(actual)));
}

void expectClose(const std::vector<double>& expected, const std::vector<double>& actual, Tolerance tolerance, const std::string& what)
{
    ASSERT_EQ(expected.size(), actual.size()) << what;
    for (std::size_t i = 0; i < expected.size(); ++i)
    {
        EXPECT_TRUE(close(expected[i], actual[i], tolerance)) << what << "[" << i << "]: expected " << expected[i] << ", got " << actual[i]
                                                              << " (difference " << actual[i] - expected[i] << ")";
    }
}

/// A quantity that moves by more than this when every y changes by one ulp is decided by last bits.
constexpr double SENSITIVITY_LIMIT = 1e-3;

struct Agreement
{
    std::optional<Tolerance> parameters;
    std::optional<Tolerance> rms;
    std::optional<Tolerance> uncertainties;
};

/// The comparison class of a case (tools/corpus.py applies the same rules to Java reruns). For transcendental
/// fits the oracle measured how far Tracker's own result moves under one-ulp changes of y; the tolerance
/// covers 100 times that, and a quantity that moves by more than 1e-3 is not compared.
Agreement agreement(const QJsonObject& c, const QJsonObject& java)
{
    const std::string kind = text(c[QStringLiteral("agreement")]);
    if (kind == "exact")
    {
        return {.parameters = EXACT, .rms = EXACT, .uncertainties = EXACT};
    }
    if (kind == "chaotic")
    {
        return {};
    }
    const QJsonObject sensitivity = java[QStringLiteral("sensitivity")].toObject();
    const auto relaxed = [&sensitivity](Tolerance base, const char* key) -> std::optional<Tolerance>
    {
        const double moved = sensitivity[QLatin1String(key)].toDouble();
        if (moved > SENSITIVITY_LIMIT)
        {
            return std::nullopt;
        }
        return Tolerance{.relative = std::max(base.relative, 100 * moved), .absolute = base.absolute};
    };
    const auto uncertainties = relaxed(TRANSCENDENTAL_UNCERTAINTIES, "uncertainties");
    if (kind == "polynomial")
    {
        // Closed-form coefficients are exact; the uncertainty refits evaluate x^3 with Math.pow.
        return {.parameters = EXACT, .rms = EXACT, .uncertainties = uncertainties};
    }
    return {.parameters = relaxed(TRANSCENDENTAL_PARAMETERS, "parameters"),
            .rms = relaxed(TRANSCENDENTAL_PARAMETERS, "rms"),
            .uncertainties = uncertainties};
}

std::vector<QJsonObject> cases()
{
    std::vector<QJsonObject> result;
    for (const auto& item : reference()[QStringLiteral("cases")].toArray())
    {
        result.push_back(item.toObject());
    }
    return result;
}

std::string defect(const QJsonObject& c)
{
    return text(c[QStringLiteral("defect")]);
}

std::vector<std::vector<double>> band(const QJsonValue& value)
{
    std::vector<std::vector<double>> result;
    for (const auto& row : value.toArray())
    {
        result.push_back(numbers(row));
    }
    return result;
}

void expectMethod(const std::string& java, const FitResult& result, const std::string& id)
{
    static const std::map<std::string, std::pair<FitMethod, std::optional<FitStatus>>> methods = {
        {"none", {FitMethod::None, std::nullopt}},
        {"closed-form", {FitMethod::ClosedForm, std::nullopt}},
        {"hessian", {FitMethod::Hessian, FitStatus::Fitted}},
        {"levenberg-marquardt", {FitMethod::LevenbergMarquardt, FitStatus::Fitted}},
        {"restored", {FitMethod::LevenbergMarquardt, FitStatus::NotImproved}},
    };
    const auto& [method, status] = methods.at(java);
    EXPECT_EQ(method, result.method) << id << " method " << java;
    if (status)
    {
        EXPECT_EQ(*status, result.status) << id << " status " << java;
    }
}

void expectJavaResult(const QJsonObject& c, const QJsonObject& java, const FitResult& result, const std::string& id)
{
    const Agreement tolerance = agreement(c, java);
    EXPECT_EQ(static_cast<std::size_t>(java[QStringLiteral("points")].toInt()), result.points) << id;
    EXPECT_TRUE(close(number(java[QStringLiteral("correlation")]), result.correlation, EXACT)) << id << " correlation";
    if (text(c[QStringLiteral("agreement")]) == "chaotic")
    {
        return;
    }
    if (tolerance.parameters)
    {
        // The path is as reproducible as the parameters it produces.
        expectMethod(text(java[QStringLiteral("method")]), result, id);
        EXPECT_EQ(java[QStringLiteral("non_real")].toBool(), result.nonRealValues) << id;
        expectClose(numbers(java[QStringLiteral("parameters")]), result.parameters, *tolerance.parameters, id + " parameters");
    }
    if (tolerance.rms)
    {
        EXPECT_TRUE(close(number(java[QStringLiteral("rms")]), result.rmsDeviation, *tolerance.rms))
            << id << " rms " << number(java[QStringLiteral("rms")]) << " vs " << result.rmsDeviation;
    }
    if (!tolerance.uncertainties)
    {
        return;
    }
    if (java[QStringLiteral("uncertainties")].isArray())
    {
        expectClose(numbers(java[QStringLiteral("uncertainties")]), result.uncertainties, *tolerance.uncertainties, id + " uncertainties");
    }
    else
    {
        EXPECT_TRUE(result.uncertainties.empty()) << id;
    }
    const auto javaBand = band(java[QStringLiteral("band")]);
    ASSERT_EQ(javaBand.size(), result.uncertaintyBand.size()) << id << " band";
    for (std::size_t i = 0; i < javaBand.size(); ++i)
    {
        expectClose(javaBand[i], result.uncertaintyBand[i], *tolerance.uncertainties, id + " band " + std::to_string(i));
    }
}

