TEST(CurveFitReference, JavaMatchesIndependentExpectations)
{
    // Exact least squares, Gauss-Newton minima and synthetic parameters computed without OSP; cases
    // marked as defects are where Tracker is known to deviate.
    int checked = 0;
    for (const QJsonObject& c : cases())
    {
        if (!c.contains(QStringLiteral("expect")) || c.contains(QStringLiteral("defect")))
        {
            continue;
        }
        const std::string id = text(c[QStringLiteral("id")]);
        const QJsonObject expect = c[QStringLiteral("expect")].toObject();
        const QJsonObject parameterTolerance = expect[QStringLiteral("parameter_tolerance")].toObject();
        const Tolerance tolerance{.relative = parameterTolerance[QStringLiteral("relative")].toDouble(),
                                  .absolute = parameterTolerance[QStringLiteral("absolute")].toDouble()};
        const QJsonObject java = c[QStringLiteral("java")].toObject();
        expectClose(numbers(expect[QStringLiteral("parameters")]), numbers(java[QStringLiteral("parameters")]), tolerance, id);
        if (expect[QStringLiteral("uncertainties")].isArray() && java[QStringLiteral("uncertainties")].isArray())
        {
            expectClose(numbers(expect[QStringLiteral("uncertainties")]),
                        numbers(java[QStringLiteral("uncertainties")]),
                        {.relative = expect[QStringLiteral("uncertainty_relative")].toDouble(), .absolute = 0.0},
                        id + " uncertainties");
        }
        ++checked;
    }
    EXPECT_GE(checked, 60);
}

