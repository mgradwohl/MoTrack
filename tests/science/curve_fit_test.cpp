/// The FitMethod and, where it is implied, FitStatus of the oracle's main-fit path.
std::pair<FitMethod, std::optional<FitStatus>> javaPath(const std::string& java)
{
    static const std::map<std::string, std::pair<FitMethod, std::optional<FitStatus>>> methods = {
        {"none", {FitMethod::None, std::nullopt}},
        {"closed-form", {FitMethod::ClosedForm, std::nullopt}},
        {"hessian", {FitMethod::Hessian, FitStatus::Fitted}},
        {"levenberg-marquardt", {FitMethod::LevenbergMarquardt, FitStatus::Fitted}},
        {"restored", {FitMethod::LevenbergMarquardt, FitStatus::NotImproved}},
    };
    return methods.at(java);
}

bool samePath(const std::string& java, const FitResult& result)
{
    const auto [method, status] = javaPath(java);
    return method == result.method && (!status || *status == result.status);
}

/// Whether a main-fit path minimized: Newton's result, the Levenberg-Marquardt fallback or the restored start.
bool minimizerPath(const std::string& java)
{
    return java == "hessian" || java == "levenberg-marquardt" || java == "restored";
}

bool minimizerPath(const FitResult& result)
{
    return result.method == FitMethod::Hessian || result.method == FitMethod::LevenbergMarquardt;
}

void expectMethod(const std::string& java, const FitResult& result, const std::string& id)
{
    const auto [method, status] = javaPath(java);
    EXPECT_EQ(method, result.method) << id << " method " << java;
    if (status)
    {
        EXPECT_EQ(*status, result.status) << id << " status " << java;
    }
}

/// A fit reported as Fitted never ends above the deviation Java's minimization started from.
void expectNoWorseThanTheStart(const QJsonObject& java, const FitResult& result, const std::string& id)
{
    const QJsonValue start = java[QStringLiteral("start")];
    if (!start.isObject() || result.status != FitStatus::Fitted || !std::isfinite(result.rmsDeviation))
    {
        return;
    }
    const double startDeviation = number(start.toObject()[QStringLiteral("ssr")]);
    const double deviation = result.rmsDeviation * result.rmsDeviation * static_cast<double>(result.points);
    EXPECT_LE(deviation, (startDeviation * (1 + 1e-9)) + 1e-300) << id << " deviation above the start";
}

void expectJavaResult(const QJsonObject& c, const QJsonObject& java, const FitResult& result, const std::string& id)
{
    const Agreement tolerance = agreement(c, java);
    EXPECT_EQ(static_cast<std::size_t>(java[QStringLiteral("points")].toInt()), result.points) << id;
    EXPECT_TRUE(close(number(java[QStringLiteral("correlation")]), result.correlation, EXACT)) << id << " correlation";
    expectNoWorseThanTheStart(java, result, id);
    if (text(c[QStringLiteral("agreement")]) == "chaotic")
    {
        // Newton diverged in Java, so the Levenberg-Marquardt fallback's outcome depends on last bits; the
        // values compare only where this port's libm led it down the same path.
        if (samePath(text(java[QStringLiteral("method")]), result))
        {
            expectClose(numbers(java[QStringLiteral("parameters")]), result.parameters, TRANSCENDENTAL_PARAMETERS, id + " parameters");
        }
        return;
    }
    if (tolerance.parameters)
    {
        // The path is as reproducible as the parameters it produces, except for a tied fit, which ends at the
        // deviation it started from (a start already at the minimum): Newton's result, the Levenberg-Marquardt
        // fallback and the restored start then differ in the last bits, so a transcendental fit may take any of
        // them that reaches the same parameters.
        const std::string method = text(java[QStringLiteral("method")]);
        const bool tied = java[QStringLiteral("tied")].toBool() && text(c[QStringLiteral("agreement")]) == "transcendental";
        if (!tied || !minimizerPath(method) || !minimizerPath(result))
        {
            expectMethod(method, result, id);
        }
        EXPECT_EQ(java[QStringLiteral("non_real")].toBool(), result.nonRealValues) << id;
        expectClose(numbers(java[QStringLiteral("parameters")]), result.parameters, *tolerance.parameters, id + " parameters");
    }
    if (tolerance.rms)
    {
        EXPECT_TRUE(close(number(java[QStringLiteral("rms")]), result.rmsDeviation, *tolerance.rms))
            << id << " rms " << number(java[QStringLiteral("rms")]) << " vs " << result.rmsDeviation;
    }
    if (!tolerance.uncertainties)
    {
        return;
    }
    if (java[QStringLiteral("uncertainties")].isArray())
    {
        expectClose(numbers(java[QStringLiteral("uncertainties")]), result.uncertainties, *tolerance.uncertainties, id + " uncertainties");
    }
    else
    {
        EXPECT_TRUE(result.uncertainties.empty()) << id;
    }
    const auto javaBand = band(java[QStringLiteral("band")]);
    ASSERT_EQ(javaBand.size(), result.uncertaintyBand.size()) << id << " band";
    for (std::size_t i = 0; i < javaBand.size(); ++i)
    {
        expectClose(javaBand[i], result.uncertaintyBand[i], *tolerance.uncertainties, id + " band " + std::to_string(i));
    }
}

