const QJsonObject& reference()
{
    static const QJsonObject document = []
    {
        QFile file(QStringLiteral(MOTRACK_FIT_REFERENCE));
        if (!file.open(QIODevice::ReadOnly))
        {
            return QJsonObject{};
        }
        return QJsonDocument::fromJson(file.readAll()).object();
    }();
    return document;
}

std::string text(const QJsonValue& value)
{
    return value.toString().toStdString();
}

double number(const QJsonValue& value)
{
    if (value.isString())
    {
        const QString s = value.toString();
        if (s == QStringLiteral("NaN"))
        {
            return NOT_A_NUMBER;
        }
        return s.startsWith(QLatin1Char('-')) ? -std::numeric_limits<double>::infinity() : std::numeric_limits<double>::infinity();
    }
    return value.toDouble();
}

std::vector<double> numbers(const QJsonValue& value)
{
    std::vector<double> result;
    for (const auto& item : value.toArray())
    {
        result.push_back(number(item));
    }
    return result;
}

std::vector<bool> flags(const QJsonValue& value)
{
    std::vector<bool> result;
    for (const auto& item : value.toArray())
    {
        result.push_back(item.toBool());
    }
    return result;
}

const std::map<std::string, BuiltInFit>& builtInIds()
{
    static const std::map<std::string, BuiltInFit> ids = {
        {"line", BuiltInFit::Line},
        {"parabola", BuiltInFit::Parabola},
        {"cubic", BuiltInFit::Cubic},
        {"gaussian", BuiltInFit::Gaussian},
        {"exponential", BuiltInFit::Exponential},
        {"sinusoid", BuiltInFit::Sinusoid},
        {"dampedsine", BuiltInFit::DampedSine},
        {"power", BuiltInFit::Power},
        {"log", BuiltInFit::Log},
    };
    return ids;
}

/// The fit a case names: a built-in, or a user fit with its fixture expression and starting values.
FitFunction caseFunction(const std::string& id)
{
    if (const auto found = builtInIds().find(id); found != builtInIds().end())
    {
        return motrack::science::builtInFit(found->second);
    }
    for (const auto& item : reference()[QStringLiteral("user_fits")].toArray())
    {
        const QJsonObject user = item.toObject();
        if (text(user[QStringLiteral("id")]) != id)
        {
            continue;
        }
        FitFunction f;
        f.name = text(user[QStringLiteral("name")]);
        f.expression = text(user[QStringLiteral("expression")]);
        const auto names = user[QStringLiteral("parameters")].toArray();
        const auto values = numbers(user[QStringLiteral("values")]);
        for (qsizetype i = 0; i < names.size(); ++i)
        {
            f.parameters.push_back(
                {.name = names[i].toString().toStdString(), .value = values[static_cast<std::size_t>(i)], .description = {}});
        }
        f.model = userModels().at(f.expression);
        return f;
    }
    ADD_FAILURE() << "unknown fit " << id;
    return {};
}

struct CaseData
{
    std::vector<double> x;
    std::vector<double> y;
};

CaseData caseData(const QJsonObject& c)
{
    if (c.contains(QStringLiteral("generated")))
    {
        const QJsonObject generated = c[QStringLiteral("generated")].toObject();
        const int rows = generated[QStringLiteral("rows")].toInt();
        const int head = generated[QStringLiteral("head")].toInt();
        const double headY = generated[QStringLiteral("head_y")].toDouble();
        CaseData data;
        for (int i = 0; i < rows; ++i)
        {
            data.x.push_back(i);
            data.y.push_back(i < head ? headY : (2.0 * i) + 1.0);
        }
        return data;
    }
    return {.x = numbers(c[QStringLiteral("x")]), .y = numbers(c[QStringLiteral("y")])};
}

FitResult runCase(const QJsonObject& c, FitDialect dialect, const std::string& fitId)
{
    FitFunction f = caseFunction(fitId);
    if (c[QStringLiteral("initial")].isArray())
    {
        const auto initial = numbers(c[QStringLiteral("initial")]);
        for (std::size_t i = 0; i < initial.size(); ++i)
        {
            f.parameters[i].value = initial[i];
        }
    }
    FitOptions options;
    options.dialect = dialect;
    options.autofit = c[QStringLiteral("autofit")].toBool();
    options.start = text(c[QStringLiteral("start")]) == "scratch" ? FitStart::FromScratch : FitStart::FromCurrent;
    if (c[QStringLiteral("fixed")].isArray())
    {
        options.fixed = flags(c[QStringLiteral("fixed")]);
    }
    const CaseData data = caseData(c);
    return motrack::science::fitCurve(f, data.x, data.y, options);
}

