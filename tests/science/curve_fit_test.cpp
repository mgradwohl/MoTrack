TEST(CurveFitReference, BuiltInFitsMatchOspDefinitions)
{
    const auto fits = reference()[QStringLiteral("fits")].toArray();
    ASSERT_EQ(static_cast<std::size_t>(fits.size()), ALL_BUILT_IN_FITS.size());
    for (std::size_t k = 0; k < ALL_BUILT_IN_FITS.size(); ++k)
    {
        const QJsonObject java = fits[static_cast<qsizetype>(k)].toObject();
        const FitFunction f = motrack::science::builtInFit(ALL_BUILT_IN_FITS[k]);
        EXPECT_EQ(builtInIds().at(text(java[QStringLiteral("id")])), ALL_BUILT_IN_FITS[k]);
        EXPECT_EQ(text(java[QStringLiteral("name")]), f.name);
        EXPECT_EQ(text(java[QStringLiteral("display_name")]), motrack::science::builtInFitDisplayName(ALL_BUILT_IN_FITS[k]));
        EXPECT_EQ(text(java[QStringLiteral("description")]), f.description);
        EXPECT_EQ(text(java[QStringLiteral("expression")]), f.expression);
        EXPECT_EQ(java[QStringLiteral("polynomial")].toBool(), f.polynomialDegree > 0);
        EXPECT_EQ(f.builtIn, ALL_BUILT_IN_FITS[k]);
        const auto names = java[QStringLiteral("parameters")].toArray();
        const auto descriptions = java[QStringLiteral("descriptions")].toArray();
        const auto defaults = numbers(java[QStringLiteral("defaults")]);
        ASSERT_EQ(static_cast<std::size_t>(names.size()), f.parameters.size());
        for (std::size_t i = 0; i < f.parameters.size(); ++i)
        {
            EXPECT_EQ(names[static_cast<qsizetype>(i)].toString().toStdString(), f.parameters[i].name);
            EXPECT_EQ(descriptions[static_cast<qsizetype>(i)].toString().toStdString(), f.parameters[i].description);
            EXPECT_EQ(defaults[i], f.parameters[i].value);
        }
    }
}

