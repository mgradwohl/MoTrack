TEST(CurveFitReference, SubstitutionDefectsComputeTheIntendedFit)
{
    int checked = 0;
    for (const QJsonObject& c : cases())
    {
        if (defect(c) != "text-substitution")
        {
            continue;
        }
        const std::string id = text(c[QStringLiteral("id")]);
        SCOPED_TRACE(id);
        // Renaming the colliding parameter makes Java compute the fit Tracker intends.
        const QJsonObject intended = c[QStringLiteral("intended")].toObject();
        for (const FitDialect dialect : {FitDialect::Tracker, FitDialect::Corrected})
        {
            const FitResult result = runCase(c, dialect, text(c[QStringLiteral("fit")]));
            expectClose(numbers(intended[QStringLiteral("parameters")]), result.parameters, TRANSCENDENTAL_PARAMETERS, id);
            expectClose(numbers(intended[QStringLiteral("uncertainties")]), result.uncertainties, TRANSCENDENTAL_UNCERTAINTIES, id);
        }
        FitFunction f = caseFunction(text(c[QStringLiteral("fit")]));
        const auto initial = numbers(c[QStringLiteral("initial")]);
        for (std::size_t i = 0; i < initial.size(); ++i)
        {
            f.parameters[i].value = initial[i];
        }
        const std::vector<bool> fixed = c[QStringLiteral("fixed")].isArray() ? flags(c[QStringLiteral("fixed")]) : std::vector<bool>{};
        EXPECT_FALSE(motrack::science::trackerSubstitutionCollisions(f, fixed).empty());
        ++checked;
    }
    EXPECT_EQ(checked, 3);
}

TEST(CurveFitReference, MinimizersMatchJava)
{
    const auto objective = [](const std::string& id) -> motrack::science::MultiVarObjective
    {
        if (id == "rosenbrock")
        {
            return [](std::span<const double> p)
            {
                return (100 * (p[1] - (p[0] * p[0])) * (p[1] - (p[0] * p[0]))) + ((1 - p[0]) * (1 - p[0]));
            };
        }
        if (id == "bowl")
        {
            return [](std::span<const double> p)
            {
                return ((p[0] - 1) * (p[0] - 1)) + (10 * (p[1] - 2) * (p[1] - 2)) + (0.5 * (p[2] + 3) * (p[2] + 3)) +
                       ((p[0] - 1) * (p[1] - 2));
            };
        }
        if (id == "flat")
        {
            return [](std::span<const double> p)
            {
                return (p[0] + p[1] - 1) * (p[0] + p[1] - 1);
            };
        }
        if (id == "quartic")
        {
            return [](std::span<const double> p)
            {
                return (p[0] - 1) * (p[0] - 1) * (p[0] - 1) * (p[0] - 1);
            };
        }
        return [](std::span<const double> p)
        {
            return p[0] < 1 ? ((p[0] - 2) * (p[0] - 2)) + (p[1] * p[1]) : NOT_A_NUMBER;
        };
    };
    const auto minimizers = reference()[QStringLiteral("minimizers")].toArray();
    ASSERT_EQ(minimizers.size(), 14);
    for (const auto& item : minimizers)
    {
        const QJsonObject m = item.toObject();
        const std::string id = text(m[QStringLiteral("id")]);
        SCOPED_TRACE(id);
        std::vector<double> x = numbers(m[QStringLiteral("start")]);
        const auto f = objective(text(m[QStringLiteral("objective")]));
        if (id.starts_with("hessian/"))
        {
            const auto result = motrack::science::hessianMinimize(f, x, 20, 1e-6);
            EXPECT_TRUE(close(number(m[QStringLiteral("result")]), result.error, EXACT));
            EXPECT_EQ(m[QStringLiteral("iterations")].toInt(), result.iterations);
        }
        else
        {
            const auto result = motrack::science::levenbergMarquardtMinimize(f, x, 20, 1e-6);
            EXPECT_EQ(m[QStringLiteral("result")].toBool(), result.converged);
            EXPECT_EQ(m[QStringLiteral("iterations")].toInt(), result.iterations);
        }
        expectClose(numbers(m[QStringLiteral("parameters")]), x, EXACT, id);
    }
}

TEST(CurveFitReference, UncertaintyTextMatchesJava)
{
    for (const auto& item : reference()[QStringLiteral("format")].toArray())
    {
        const QJsonObject probe = item.toObject();
        const auto formatted = motrack::science::formatUncertainParameter(
            number(probe[QStringLiteral("value")]), number(probe[QStringLiteral("sigma")]), probe[QStringLiteral("extra_places")].toInt());
        if (probe[QStringLiteral("text")].isNull())
        {
            EXPECT_FALSE(formatted.has_value());
        }
        else
        {
            ASSERT_TRUE(formatted.has_value());
            EXPECT_EQ(text(probe[QStringLiteral("text")]), *formatted);
        }
    }
    // Every fitted parameter shown with its uncertainty in the oracle cases.
    for (const QJsonObject& c : cases())
    {
        const QJsonObject java = c[QStringLiteral("java")].toObject();
        const auto values = numbers(java[QStringLiteral("parameters")]);
        const auto sigmas = java[QStringLiteral("uncertainties")].isArray() ? numbers(java[QStringLiteral("uncertainties")])
                                                                            : std::vector<double>(values.size(), NOT_A_NUMBER);
        const auto texts = java[QStringLiteral("formatted")].toArray();
        for (std::size_t i = 0; i < values.size(); ++i)
        {
            const auto formatted = motrack::science::formatUncertainParameter(values[i], i < sigmas.size() ? sigmas[i] : NOT_A_NUMBER);
            const QJsonValue expected = texts[static_cast<qsizetype>(i)];
            EXPECT_EQ(expected.isNull(), !formatted.has_value()) << text(c[QStringLiteral("id")]);
            if (formatted && !expected.isNull())
            {
                EXPECT_EQ(text(expected), *formatted) << text(c[QStringLiteral("id")]);
            }
        }
    }
}

